const fs = require('fs');
const content = [
'"use client";',
'import { useState, useEffect } from "react";',
'import { useAccount, useWriteContract, useWaitForTransactionReceipt, useReadContract } from "wagmi";',
'import { useRouter } from "next/navigation";',
'import { parseUnits, formatUnits } from "viem";',
'import { BottomNav } from "@/components/BottomNav";',
'import { useWalletBalance } from "@/lib/useWalletBalance";',
'import { useAppSettings } from "@/components/SettingsContext";',
'import { translations } from "@/lib/translations";',
'import { USDC_ADDRESS, EURC_ADDRESS, ZARPAY_SWAP_POOL_ADDRESS, ERC20_ABI, ZARPAY_SWAP_POOL_ABI, TOKEN_DECIMALS } from "@/lib/contracts";',
'',
'const TOKENS = [',
'  { symbol: "USDC", name: "USD Coin",  color: "#2775ca", bg: "rgba(39,117,202,0.15)" },',
'  { symbol: "EURC", name: "Euro Coin", color: "#4ade80", bg: "rgba(74,222,128,0.15)" },',
'];',
'',
'type TokenSymbol = "USDC" | "EURC";',
'const TOKEN_ADDRESSES: Record<TokenSymbol, `0x${string}`> = { USDC: USDC_ADDRESS, EURC: EURC_ADDRESS };',
'',
'export default function ExchangePage() {',
'  const { address, isConnected } = useAccount();',
'  const router = useRouter();',
'  const { settings } = useAppSettings();',
'  const tr = translations[settings.language] ?? translations.English;',
'  const [mounted, setMounted] = useState(false);',
'  const [fromToken, setFromToken] = useState<TokenSymbol>("USDC");',
'  const [toToken, setToToken] = useState<TokenSymbol>("EURC");',
'  const [fromAmount, setFromAmount] = useState("");',
'  const [showFromPicker, setShowFromPicker] = useState(false);',
'  const [showToPicker, setShowToPicker] = useState(false);',
'  const [step, setStep] = useState<"idle"|"approving"|"swapping"|"success"|"error">("idle");',
'  const [netOut, setNetOut] = useState("");',
'  const [feeAmount, setFeeAmount] = useState("");',
'  const [errorMsg, setErrorMsg] = useState("");',
'',
'  useEffect(() => { setMounted(true); }, []);',
'  useEffect(() => { if (mounted && !isConnected) router.push("/"); }, [mounted, isConnected, router]);',
'',
'  const { usdcFormatted, eurcFormatted, refetch: refetchBalance } = useWalletBalance(address);',
'',
'  const isDark = settings.theme === "dark";',
'  const bg = isDark ? "#0a0f14" : "#f0f4f8";',
'  const cardBg = isDark ? "#0e1318" : "#ffffff";',
'  const cardBorder = isDark ? "#1f2937" : "#e2e8f0";',
'  const inputBg = isDark ? "#111827" : "#f8fafc";',
'  const textPrimary = isDark ? "white" : "#0a0f14";',
'  const textMuted = isDark ? "#4b5563" : "#94a3b8";',
'',
'  const isUsdcToEurc = fromToken === "USDC";',
'  const amountIn = fromAmount && Number(fromAmount) > 0 ? parseUnits(fromAmount, TOKEN_DECIMALS) : BigInt(0);',
'',
'  const { refetch: refetchPreview } = useReadContract({',
'    address: ZARPAY_SWAP_POOL_ADDRESS,',
'    abi: ZARPAY_SWAP_POOL_ABI,',
'    functionName: "previewSwapAfterFee",',
'    args: [amountIn, isUsdcToEurc],',
'    query: { enabled: false },',
'  });',
'',
'  const { data: allowance, refetch: refetchAllowance } = useReadContract({',
'    address: TOKEN_ADDRESSES[fromToken],',
'    abi: ERC20_ABI,',
'    functionName: "allowance",',
'    args: address ? [address, ZARPAY_SWAP_POOL_ADDRESS] : undefined,',
'    query: { enabled: !!address },',
'  });',
'',
'  const needsApproval = !allowance || allowance < amountIn;',
'',
'  const { writeContract: writeApprove, data: approveHash, error: approveError, reset: resetApprove } = useWriteContract();',
'  const { writeContract: writeSwap, data: swapHash, error: swapError, reset: resetSwap } = useWriteContract();',
'  const { isLoading: approveConfirming, isSuccess: approveConfirmed } = useWaitForTransactionReceipt({ hash: approveHash });',
'  const { isLoading: swapConfirming, isSuccess: swapConfirmed } = useWaitForTransactionReceipt({ hash: swapHash });',
'',
'  useEffect(() => {',
'    if (approveConfirmed && step === "approving") { refetchAllowance(); runSwap(); }',
'  }, [approveConfirmed]);',
'',
'  useEffect(() => {',
'    if (swapConfirmed && step === "swapping") {',
'      setStep("success");',
'      refetchBalance();',
'      refetchPreview();',
'    }',
'  }, [swapConfirmed]);',
'',
'  useEffect(() => {',
'    if (approveError) { setStep("error"); setErrorMsg(approveError.message || "Approval failed."); }',
'    if (swapError) { setStep("error"); setErrorMsg(swapError.message || "Swap failed."); }',
'  }, [approveError, swapError]);',
'',
'  useEffect(() => {',
'    if (amountIn > BigInt(0)) {',
'      refetchPreview().then((res) => {',
'        const data = res.data as [bigint, bigint] | undefined;',
'        if (data) {',
'          setNetOut(formatUnits(data[0], TOKEN_DECIMALS));',
'          setFeeAmount(formatUnits(data[1], TOKEN_DECIMALS));',
'        }',
'      });',
'    } else {',
'      setNetOut(""); setFeeAmount("");',
'    }',
'  }, [fromAmount, fromToken, toToken]);',
'',
'  function handleFlip() {',
'    setFromToken(toToken); setToToken(fromToken); setFromAmount(""); setNetOut(""); setFeeAmount("");',
'  }',
'',
'  function runSwap() {',
'    setStep("swapping");',
'    writeSwap({',
'      address: ZARPAY_SWAP_POOL_ADDRESS,',
'      abi: ZARPAY_SWAP_POOL_ABI,',
'      functionName: isUsdcToEurc ? "swapUSDCtoEURC" : "swapEURCtoUSDC",',
'      args: [amountIn],',
'    });',
'  }',
'',
'  function handleSwap() {',
'    if (!fromAmount || Number(fromAmount) <= 0 || fromToken === toToken) return;',
'    resetApprove(); resetSwap(); setErrorMsg("");',
'    if (needsApproval) {',
'      setStep("approving");',
'      writeApprove({ address: TOKEN_ADDRESSES[fromToken], abi: ERC20_ABI, functionName: "approve", args: [ZARPAY_SWAP_POOL_ADDRESS, amountIn] });',
'    } else { runSwap(); }',
'  }',
'',
'  function handleReset() {',
'    setStep("idle"); setFromAmount(""); setNetOut(""); setFeeAmount(""); setErrorMsg(""); resetApprove(); resetSwap();',
'  }',
'',
'  const isPending = step === "approving" || step === "swapping" || approveConfirming || swapConfirming;',
'  const pendingLabel = step === "approving"',
'    ? (approveConfirming ? "Confirming approval on-chain..." : "Waiting for wallet confirmation...")',
'    : (swapConfirming ? "Confirming swap on-chain..." : "Waiting for wallet confirmation...");',
'',
'  function TokenPicker({ selected, onSelect, onClose }: { selected: string; onSelect: (s: string) => void; onClose: () => void }) {',
'    return (',
'      <div style={{ position: "fixed", inset: 0, background: "rgba(0,0,0,0.75)", zIndex: 200, display: "flex", alignItems: "flex-end", justifyContent: "center", padding: "16px" }} onClick={onClose}>',
'        <div style={{ width: "100%", maxWidth: "440px", background: cardBg, border: `1px solid ${cardBorder}`, borderRadius: "20px", padding: "24px", marginBottom: "8px" }} onClick={e => e.stopPropagation()}>',
'          <div style={{ display: "flex", justifyContent: "space-between", alignItems: "center", marginBottom: "20px" }}>',
'            <p style={{ color: textPrimary, fontSize: "16px", fontWeight: "700" }}>Select Token</p>',
'            <button onClick={onClose} style={{ color: textMuted, background: "none", border: "none", fontSize: "20px", cursor: "pointer" }}>✕</button>',
'          </div>',
'          <div style={{ display: "flex", flexDirection: "column", gap: "8px" }}>',
'            {TOKENS.map(token => (',
'              <button key={token.symbol} onClick={() => { onSelect(token.symbol); onClose(); }} style={{ display: "flex", alignItems: "center", gap: "12px", padding: "14px", background: selected === token.symbol ? "rgba(74,222,128,0.08)" : inputBg, border: `1px solid ${selected === token.symbol ? "rgba(74,222,128,0.3)" : cardBorder}`, borderRadius: "12px", cursor: "pointer", width: "100%" }}>',
'                <div style={{ width: "40px", height: "40px", borderRadius: "50%", background: token.bg, border: `1px solid ${token.color}40`, display: "flex", alignItems: "center", justifyContent: "center", flexShrink: 0 }}>',
'                  <span style={{ color: token.color, fontSize: "12px", fontWeight: "700", fontFamily: "monospace" }}>{token.symbol.slice(0, 2)}</span>',
'                </div>',
'                <div style={{ textAlign: "left" }}>',
'                  <p style={{ color: textPrimary, fontSize: "14px", fontWeight: "600" }}>{token.symbol}</p>',
'                  <p style={{ color: textMuted, fontSize: "12px", fontFamily: "monospace" }}>{token.name}</p>',
'                </div>',
'                {selected === token.symbol && <span style={{ marginLeft: "auto", color: "#4ade80", fontSize: "16px" }}>✓</span>}',
'              </button>',
'            ))}',
'          </div>',
'        </div>',
'      </div>',
'    );',
'  }',
'',
'  if (!mounted) return null;',
'  const fromTokenData = TOKENS.find(t => t.symbol === fromToken)!;',
'  const toTokenData = TOKENS.find(t => t.symbol === toToken)!;',
'',
'  return (',
'    <main style={{ minHeight: "100vh", background: bg, padding: "24px 16px 100px", display: "flex", flexDirection: "column", alignItems: "center", transition: "background 0.3s" }}>',
'      {showFromPicker && <TokenPicker selected={fromToken} onSelect={s => { setFromToken(s as TokenSymbol); if (s === toToken) setToToken(fromToken); }} onClose={() => setShowFromPicker(false)} />}',
'      {showToPicker && <TokenPicker selected={toToken} onSelect={s => { setToToken(s as TokenSymbol); if (s === fromToken) setFromToken(toToken); }} onClose={() => setShowToPicker(false)} />}',
'',
'      <div style={{ width: "100%", maxWidth: "440px", display: "flex", alignItems: "center", marginBottom: "24px" }}>',
'        <h1 style={{ color: textPrimary, fontSize: "20px", fontWeight: "700" }}>{tr.exchange}</h1>',
'        <div style={{ marginLeft: "auto", background: "rgba(74,222,128,0.1)", border: "1px solid rgba(74,222,128,0.2)", borderRadius: "8px", padding: "4px 10px" }}>',
'          <span style={{ color: "#4ade80", fontSize: "11px", fontFamily: "monospace" }}>Arc Testnet</span>',
'        </div>',
'      </div>',
'',
'      {(step === "idle" || isPending) && (',
'      <div style={{ width: "100%", maxWidth: "440px", background: cardBg, border: `1px solid ${cardBorder}`, borderRadius: "20px", padding: "20px", marginBottom: "16px" }}>',
'        <div style={{ marginBottom: "8px" }}>',
'          <p style={{ color: textMuted, fontSize: "11px", fontFamily: "monospace", textTransform: "uppercase", letterSpacing: "0.1em", marginBottom: "8px" }}>You Pay</p>',
'          <div style={{ background: inputBg, border: `1px solid ${cardBorder}`, borderRadius: "14px", padding: "16px", display: "flex", alignItems: "center", gap: "12px" }}>',
'            <button onClick={() => setShowFromPicker(true)} style={{ display: "flex", alignItems: "center", gap: "8px", background: fromTokenData.bg, border: `1px solid ${fromTokenData.color}40`, borderRadius: "10px", padding: "8px 12px", cursor: "pointer", flexShrink: 0 }}>',
'              <span style={{ color: fromTokenData.color, fontSize: "12px", fontWeight: "700", fontFamily: "monospace" }}>{fromToken.slice(0,2)}</span>',
'              <span style={{ color: textPrimary, fontSize: "14px", fontWeight: "700" }}>{fromToken}</span>',
'              <span style={{ color: textMuted, fontSize: "10px" }}>▾</span>',
'            </button>',
'            <input type="number" placeholder="0.00" value={fromAmount} onChange={e => setFromAmount(e.target.value)} min="0" step="0.001" style={{ flex: 1, background: "none", border: "none", outline: "none", color: textPrimary, fontSize: "22px", fontWeight: "800", fontFamily: "monospace", textAlign: "right", width: "0" }} />',
'          </div>',
'          <p style={{ color: textMuted, fontSize: "11px", fontFamily: "monospace", marginTop: "6px", textAlign: "right" }}>',
'            Balance: {fromToken === "USDC" ? usdcFormatted : eurcFormatted} {fromToken}',
'          </p>',
'        </div>',
'',
'        <div style={{ display: "flex", justifyContent: "center", margin: "4px 0" }}>',
'          <button onClick={handleFlip} style={{ width: "36px", height: "36px", borderRadius: "50%", background: bg, border: `1px solid ${cardBorder}`, display: "flex", alignItems: "center", justifyContent: "center", cursor: "pointer", color: "#4ade80", fontSize: "16px" }}>⇅</button>',
'        </div>',
'',
'        <div>',
'          <p style={{ color: textMuted, fontSize: "11px", fontFamily: "monospace", textTransform: "uppercase", letterSpacing: "0.1em", marginBottom: "8px" }}>You Receive</p>',
'          <div style={{ background: inputBg, border: `1px solid ${cardBorder}`, borderRadius: "14px", padding: "16px", display: "flex", alignItems: "center", gap: "12px" }}>',
'            <button onClick={() => setShowToPicker(true)} style={{ display: "flex", alignItems: "center", gap: "8px", background: toTokenData.bg, border: `1px solid ${toTokenData.color}40`, borderRadius: "10px", padding: "8px 12px", cursor: "pointer", flexShrink: 0 }}>',
'              <span style={{ color: toTokenData.color, fontSize: "12px", fontWeight: "700", fontFamily: "monospace" }}>{toToken.slice(0,2)}</span>',
'              <span style={{ color: textPrimary, fontSize: "14px", fontWeight: "700" }}>{toToken}</span>',
'              <span style={{ color: textMuted, fontSize: "10px" }}>▾</span>',
'            </button>',
'            <p style={{ flex: 1, color: netOut ? "#4ade80" : textMuted, fontSize: "22px", fontWeight: "800", fontFamily: "monospace", textAlign: "right" }}>{netOut || "0.00"}</p>',
'          </div>',
'        </div>',
'      </div>',
'      )}',
'',
'      {Number(fromAmount) > 0 && netOut && step === "idle" && (',
'        <div style={{ width: "100%", maxWidth: "440px", background: cardBg, border: `1px solid ${cardBorder}`, borderRadius: "16px", padding: "16px", marginBottom: "16px" }}>',
'          <p style={{ color: textMuted, fontSize: "11px", fontFamily: "monospace", textTransform: "uppercase", letterSpacing: "0.1em", marginBottom: "12px" }}>Swap Preview</p>',
'          {[',
'            { label: "Rate (on-chain)", value: `1 ${fromToken} ≈ ${netOut && fromAmount ? (Number(netOut)/Number(fromAmount)).toFixed(4) : "-"} ${toToken}` },',
'            { label: "ZarPay Fee (0.5%)", value: `${feeAmount} ${toToken}` },',
'            { label: "You get", value: `${netOut} ${toToken}` },',
'            { label: "Network", value: "Arc Testnet" },',
'          ].map((row, i) => (',
'            <div key={i} style={{ display: "flex", justifyContent: "space-between", paddingBottom: "10px", marginBottom: "10px", borderBottom: i < 3 ? `1px solid ${cardBorder}` : "none" }}>',
'              <span style={{ color: textMuted, fontSize: "12px", fontFamily: "monospace" }}>{row.label}</span>',
'              <span style={{ color: i === 2 ? "#4ade80" : textPrimary, fontSize: "12px", fontFamily: "monospace", fontWeight: i === 2 ? "700" : "400" }}>{row.value}</span>',
'            </div>',
'          ))}',
'        </div>',
'      )}',
'',
'      {isPending && (',
'        <div style={{ width: "100%", maxWidth: "440px", background: cardBg, border: `1px solid ${cardBorder}`, borderRadius: "16px", padding: "32px", display: "flex", flexDirection: "column", alignItems: "center", gap: "16px", marginBottom: "16px" }}>',
'          <div style={{ width: "48px", height: "48px", borderRadius: "50%", border: `4px solid ${cardBorder}`, borderTop: "4px solid #4ade80", animation: "spin 1s linear infinite" }} />',
'          <style>{`@keyframes spin { to { transform: rotate(360deg); } }`}</style>',
'          <p style={{ color: textPrimary, fontWeight: "700", fontSize: "16px", textAlign: "center" }}>{pendingLabel}</p>',
'          {step === "approving" && <p style={{ color: textMuted, fontSize: "12px", fontFamily: "monospace", textAlign: "center" }}>Step 1 of 2 — approval, then swap</p>}',
'        </div>',
'      )}',
'',
'      {step === "success" && (',
'        <div style={{ width: "100%", maxWidth: "440px", background: cardBg, border: "1px solid rgba(74,222,128,0.3)", borderRadius: "16px", padding: "32px", display: "flex", flexDirection: "column", alignItems: "center", gap: "12px", marginBottom: "16px" }}>',
'          <div style={{ width: "56px", height: "56px", borderRadius: "50%", background: "rgba(74,222,128,0.1)", border: "1px solid rgba(74,222,128,0.3)", display: "flex", alignItems: "center", justifyContent: "center" }}>',
'            <span style={{ color: "#4ade80", fontSize: "24px" }}>✓</span>',
'          </div>',
'          <p style={{ color: textPrimary, fontWeight: "700", fontSize: "18px" }}>Swap Complete!</p>',
'          <p style={{ color: textMuted, fontSize: "13px", fontFamily: "monospace", textAlign: "center" }}>{fromAmount} {fromToken} → {netOut} {toToken}</p>',
'          {swapHash && (',
'            <a href={`https://testnet.arcscan.app/tx/${swapHash}`} target="_blank" rel="noopener noreferrer" style={{ color: "#4ade80", fontSize: "12px", fontFamily: "monospace", textDecoration: "underline" }}>View on ArcScan ↗</a>',
'          )}',
'          <button onClick={handleReset} style={{ background: "#4ade80", color: "#111", fontWeight: "700", fontSize: "14px", borderRadius: "12px", padding: "12px 24px", border: "none", cursor: "pointer", marginTop: "8px" }}>Swap Again</button>',
'        </div>',
'      )}',
'',
'      {step === "error" && (',
'        <div style={{ width: "100%", maxWidth: "440px", background: cardBg, border: "1px solid rgba(248,113,113,0.3)", borderRadius: "16px", padding: "32px", display: "flex", flexDirection: "column", alignItems: "center", gap: "12px", marginBottom: "16px" }}>',
'          <div style={{ width: "56px", height: "56px", borderRadius: "50%", background: "rgba(248,113,113,0.1)", border: "1px solid rgba(248,113,113,0.3)", display: "flex", alignItems: "center", justifyContent: "center" }}>',
'            <span style={{ color: "#f87171", fontSize: "24px" }}>✕</span>',
'          </div>',
'          <p style={{ color: textPrimary, fontWeight: "700", fontSize: "18px" }}>Swap Failed</p>',
'          <p style={{ color: "#f87171", fontSize: "13px", fontFamily: "monospace", textAlign: "center" }}>{errorMsg}</p>',
'          <button onClick={handleReset} style={{ background: "#4ade80", color: "#111", fontWeight: "700", fontSize: "14px", borderRadius: "12px", padding: "12px 24px", border: "none", cursor: "pointer", marginTop: "8px" }}>Try Again</button>',
'        </div>',
'      )}',
'',
'      {step === "idle" && (',
'        <button onClick={handleSwap} disabled={!fromAmount || Number(fromAmount) <= 0 || fromToken === toToken} style={{ width: "100%", maxWidth: "440px", background: (!fromAmount || Number(fromAmount) <= 0 || fromToken === toToken) ? "#1f2937" : "#4ade80", color: (!fromAmount || Number(fromAmount) <= 0 || fromToken === toToken) ? "#4b5563" : "#111", fontWeight: "700", fontSize: "16px", borderRadius: "16px", padding: "18px", border: "none", cursor: (!fromAmount || Number(fromAmount) <= 0 || fromToken === toToken) ? "not-allowed" : "pointer" }}>',
'          {fromToken === toToken ? "Select different tokens" : !fromAmount ? "Enter amount" : `Swap ${fromToken} → ${toToken}`}',
'        </button>',
'      )}',
'',
'      <BottomNav />',
'    </main>',
'  );',
'}',
].join('\n');

